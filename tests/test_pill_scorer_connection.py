"""The scorer must not hold DuckDB's read lock across its LLM judging loop.

Issue #70: `score_new` opened a read-only connection and kept it open through
`pill_judge.judge(...)`. DuckDB allows many readers OR one writer, so the
ingest's writer could not open the database for the whole judging loop —
measured 302 s median, 1041 s p95, 1760 s max over 195 cycles, and the ingest
deferred 2 cycles and failed 24 in the day this was written.

What is pinned here:

1. `pill_judge.judge` is called while the scorer's read connection is CLOSED,
   and no new connection is opened before the write burst.
2. `score_new` produces the same verdicts and the same tags as the pre-#70
   implementation on a fixed fixture. `tests/fixtures/pill_scorer_golden.json`
   was generated by running the fixture through `stage_batch` at commit
   bb98352 (the code before this change), so it is evidence about the old
   behaviour, not a restatement of the new one.

Run with the repo venv (duckdb lives there):
    .venv\\Scripts\\python.exe -m pytest tests\\test_pill_scorer_connection.py -v
A plain run works too (no pytest required):
    .venv\\Scripts\\python.exe tests\\test_pill_scorer_connection.py
"""

import json
import sys
import time
from pathlib import Path

import numpy as np
import pytest

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from pipeline import pill_judge, pill_scorer  # noqa: E402

GOLDEN_PATH = Path(__file__).resolve().parent / "fixtures" / "pill_scorer_golden.json"
CRAWLED = 20261120000000

PILLS = [
    {"key": "ai_general", "kind": "curated", "hi": 0.85, "lo": 0.55, "strict": False},
    {"key": "supply_chain", "kind": "curated", "hi": 0.85, "lo": 0.55, "strict": True},
    {"key": "custom_7", "kind": "custom", "hi": 0.60, "lo": None},
    {"key": "meddev", "kind": "fda", "hi": 0.85, "lo": 0.55, "strict": False},
]

# dim 4, one basis direction per pill: cos(article, pill) == component i
PILL_VECS = {
    "ai_general": np.array([1.0, 0.0, 0.0, 0.0], dtype="float32"),
    "supply_chain": np.array([0.0, 1.0, 0.0, 0.0], dtype="float32"),
    "custom_7": np.array([0.0, 0.0, 1.0, 0.0], dtype="float32"),
    "meddev": np.array([0.0, 0.0, 0.0, 1.0], dtype="float32"),
}

# url -> (cosine to each pill, in PILLS order)
URL_COS = {
    "u1": (0.90, 0.30, 0.20),    # keyword-tagged, judged relevant -> replace row
    "u2": (0.70, 0.50, 0.40),    # keyword-tagged, judged irrelevant  -> demote
    "u3": (0.68, 0.30, 0.30),    # semantic-only candidate, borderline -> tag
    "u4": (0.30, 0.80, 0.20),    # semantic-only, borderline on a strict pill -> no tag
    "u5": (0.85, 0.20, 0.20),    # already judged -> judge must not see it
    "u6": (0.67, 0.20, 0.20),    # candidate with no usable title -> no verdict
    "u7": (0.30, 0.30, 0.75),    # custom pill member (threshold 0.60) -> tag
    "u8": (0.30, 0.20, 0.80),    # custom pill member, already tagged -> skip
    "u9": (0.20, 0.20, 0.20),    # fda_match_cache candidate -> judged
    "u10": (0.30, 0.50, 0.20),   # keyword-tagged, judged relevant, NO crawled_at
}
URLS = list(URL_COS)

JUDGE_VERDICTS = {
    "ai_general": {"u1": "relevant", "u2": "irrelevant", "u3": "borderline"},
    "supply_chain": {"u4": "borderline", "u10": "relevant"},
    "meddev": {"u9": "relevant"},
}


def _vectors() -> np.ndarray:
    rows = []
    for url in URLS:
        cos = URL_COS[url]
        residual = max(0.0, 1.0 - sum(c * c for c in cos))
        vec = np.array(list(cos) + [residual ** 0.5], dtype="float32")
        rows.append(vec / np.linalg.norm(vec))
    return np.stack(rows)


def build_fixture(db_path: Path):
    """A tiny DuckDB with only the tables the scorer reads.

    u3 lives only in `gal` (exercises the gal_recent -> gal fallback); u6 has a
    row but no usable title; u10 has no row at all, so it cannot be inserted.
    """
    import duckdb

    con = duckdb.connect(str(db_path))
    con.execute("""
        CREATE TABLE gal_recent (
            url VARCHAR, crawled_at BIGINT, published_at BIGINT, domain VARCHAR,
            outlet_name VARCHAR, outlet_logo VARCHAR, outlet_twitter VARCHAR,
            title VARCHAR, image VARCHAR, description VARCHAR, language VARCHAR
        )
    """)
    con.execute("""
        CREATE TABLE gal (
            url VARCHAR, crawled_at BIGINT, published_at BIGINT, domain VARCHAR,
            outlet_name VARCHAR, outlet_logo VARCHAR, outlet_twitter VARCHAR,
            title VARCHAR, image VARCHAR, description VARCHAR, language VARCHAR
        )
    """)
    con.execute("""
        CREATE TABLE article_tags (
            article_id VARCHAR, source_type VARCHAR, category VARCHAR,
            matched_via VARCHAR, matched_detail VARCHAR, crawled_at BIGINT
        )
    """)
    con.execute("""
        CREATE TABLE fda_match_cache (
            article_id VARCHAR, source_type VARCHAR, matched_in VARCHAR,
            matched_name VARCHAR, medical_specialties VARCHAR, crawled_at BIGINT,
            match_type VARCHAR, matched_pattern VARCHAR
        )
    """)

    gal_rows = []
    for url in URLS:
        title = f"A sufficiently long article title about {url} and its subject"
        if url == "u6":
            title = "Short"          # filtered by _titles_for (>10 chars)
        # u10 carries a title but no usable crawled_at: it can be judged and
        # approved, yet cannot be inserted (and its keyword row must survive).
        crawled = None if url == "u10" else CRAWLED
        gal_rows.append((url, crawled, CRAWLED, "example.com", "Example",
                         None, None, title, None, f"description for {url}", "en"))
    con.executemany(
        "INSERT INTO gal_recent VALUES (?,?,?,?,?,?,?,?,?,?,?)",
        [r for r in gal_rows if r[0] != "u3"],
    )
    # u3 only in gal: the fallback table must be used for title + crawled_at.
    con.executemany("INSERT INTO gal VALUES (?,?,?,?,?,?,?,?,?,?,?)",
                    [r for r in gal_rows if r[0] == "u3"])

    con.executemany(
        "INSERT INTO article_tags VALUES (?,?,?,?,?,?)",
        [
            ("u1", "gal", "ai_general", "keyword", "kw", CRAWLED),
            ("u2", "gal", "ai_general", "keyword", "kw", CRAWLED),
            ("u5", "gal", "ai_general", "keyword", "kw", CRAWLED),
            ("u5", "gal", "ai_general", "judge", "relevant|0.850", CRAWLED),
            ("u8", "gal", "custom_7", "semantic", "0.800", CRAWLED),
            ("u10", "gal", "supply_chain", "keyword", "kw", CRAWLED),
        ],
    )
    con.execute(
        "INSERT INTO fda_match_cache VALUES (?,?,?,?,?,?,?,?)",
        ("u9", "gal", "title", "Acme Medical", "", CRAWLED, "legal", "acme"),
    )
    con.close()


def make_judge(calls: list | None = None):
    """Deterministic stand-in for the LLM. Records exactly what the judge saw."""

    def judge(category, items, breaker=None, workers=1):
        if calls is not None:
            calls.append({"category": category,
                          "urls": [i["url"] for i in items],
                          "items": items})
        seen = {i["url"] for i in items}
        return {u: v for u, v in JUDGE_VERDICTS.get(category, {}).items() if u in seen}

    return judge


def _golden() -> dict:
    return json.loads(GOLDEN_PATH.read_text(encoding="utf-8"))


def _normalised(inserts) -> list:
    """Insert order is set-driven in the scorer; compare as sorted tuples."""
    return sorted([list(r) for r in inserts], key=lambda r: (r[2], r[0], r[3]))


# ---------------------------------------------------------------------------
# 1. The connection is closed before the judge runs (the actual defect)
# ---------------------------------------------------------------------------

class _RecordingConnection:
    def __init__(self, con, events: list, label: str = "read"):
        self._con = con
        self._events = events
        self._label = label
        self.closed = False
        self.opened_at = time.monotonic()
        self.closed_at = None

    def execute(self, *args, **kwargs):
        assert not self.closed, "query issued on the scorer's closed connection"
        return self._con.execute(*args, **kwargs)

    def executemany(self, *args, **kwargs):
        assert not self.closed, "query issued on the scorer's closed connection"
        return self._con.executemany(*args, **kwargs)

    def close(self):
        self.closed = True
        self.closed_at = time.monotonic()
        self._events.append(f"{self._label}-close")
        self._con.close()


def _run_score_new(monkeypatch, tmp_path, judge=None, events=None):
    """Drive score_new end to end against the fixture database."""
    import duckdb

    from pipeline import loader

    db_path = tmp_path / "fixture.duckdb"
    build_fixture(db_path)
    events = events if events is not None else []
    state = {}

    real_open_write = pill_scorer._open_connection

    def open_read(*a, **k):
        con = duckdb.connect(str(db_path), read_only=True)
        rec = _RecordingConnection(con, events)
        state["read"] = rec
        events.append("read-open")
        return rec

    def open_write(*a, **k):
        assert state["read"].closed, "write connection opened while the read connection lives"
        events.append("write-open")
        return _RecordingConnection(real_open_write(db_path, budget_s=5), events, "write")

    monkeypatch.setattr(pill_scorer, "DB_PATH", db_path)
    monkeypatch.setattr(pill_scorer, "_open_read", open_read)
    monkeypatch.setattr(pill_scorer, "_open_connection", open_write)
    monkeypatch.setattr(pill_scorer, "load_pill_defs", lambda: [dict(p) for p in PILLS])
    monkeypatch.setattr(pill_scorer, "get_pill_vectors", lambda _pills: dict(PILL_VECS))
    monkeypatch.setattr(pill_scorer.embedding_store, "total_rows", lambda: 11)
    monkeypatch.setattr(
        pill_scorer.embedding_store, "iter_active_chunks",
        lambda **_kw: iter([(URLS, _vectors(), 10)]),
    )
    watermark = tmp_path / "watermark"
    watermark.write_text("10\n")
    monkeypatch.setattr(pill_scorer, "WATERMARK", watermark)
    monkeypatch.setattr(pill_scorer, "JUDGE_HEALTH", tmp_path / "health.json")
    monkeypatch.setattr(pill_judge, "preflight", lambda _breaker: True)

    calls = []
    inner = judge or make_judge(calls)

    def asserting_judge(category, items, breaker=None, workers=1):
        # THE assertion: the scorer's read-only connection must be closed here.
        rec = state.get("read")
        assert rec is not None, "judge called before the scorer opened the database"
        assert rec.closed, (
            "pill_judge.judge was called while the scorer's read-only DuckDB "
            "connection was still open — that is the ingest-blocking defect (#70)"
        )
        events.append(f"judge:{category}")
        return inner(category, items, breaker=breaker, workers=workers)

    monkeypatch.setattr(pill_judge, "judge", asserting_judge)
    result = pill_scorer.score_new(chunk_rows=len(URLS), max_chunks=1)
    state["result"] = result
    state["calls"] = calls
    state["events"] = events
    state["watermark"] = watermark
    state["db_path"] = db_path
    return state


def test_judge_is_called_with_the_read_connection_closed(monkeypatch, tmp_path):
    state = _run_score_new(monkeypatch, tmp_path)
    events = state["events"]
    last_close = max(i for i, e in enumerate(events) if e == "read-close")
    judge_events = [i for i, e in enumerate(events) if e.startswith("judge:")]
    assert judge_events, "no judge call reached the scorer"
    assert min(judge_events) > last_close
    # ... and the read connection is opened exactly once, before judging.
    assert events.count("read-open") == 1
    seen_pills = [e.split(":", 1)[1] for e in events if e.startswith("judge:")]
    assert seen_pills == ["ai_general", "supply_chain", "meddev"], seen_pills
    # The write burst still happens, and only after judging finished.
    write_at = min(i for i, e in enumerate(events) if e == "write-open")
    assert write_at > max(judge_events)
    assert state["result"]["judged"] == 6
    assert state["result"]["db_hold_s"] < 5.0


def test_no_connection_is_reopened_between_planning_and_the_write_burst(monkeypatch, tmp_path):
    state = _run_score_new(monkeypatch, tmp_path)
    assert [e for e in state["events"] if e.endswith("-open")] == ["read-open", "write-open"]
    assert [e for e in state["events"] if e.endswith("-close")] == ["read-close", "write-close"]


def test_judge_failure_still_closes_the_connection_and_holds_the_watermark(monkeypatch, tmp_path):
    """The gateway is flaky in production; the failure path must not regress
    either the hold or the no-rewind watermark rule."""
    state = _run_score_new(monkeypatch, tmp_path, judge=lambda *a, **k: None)
    result = state["result"]
    assert result["halted_on_judge_failure"] is True
    assert result["failure_code"] == "judge_error"
    assert result["judged"] == 0
    assert result["db_hold_s"] < 5.0
    assert state["watermark"].read_text().strip() == "10"
    # Nothing was staged, so the write burst is skipped entirely.
    assert "write-open" not in state["events"]
    last_close = max(i for i, e in enumerate(state["events"]) if e == "read-close")
    first_judge = min(i for i, e in enumerate(state["events"]) if e.startswith("judge:"))
    assert first_judge > last_close


# ---------------------------------------------------------------------------
# 2. Equivalence: same input, same verdicts and tags as before the change
# ---------------------------------------------------------------------------

def _run_stage_batch(db_path: Path, calls: list):
    import duckdb

    con = duckdb.connect(str(db_path), read_only=True)
    try:
        return pill_scorer.stage_batch(
            con, URLS, _vectors(), [dict(p) for p in PILLS], dict(PILL_VECS),
            suffix="", breaker=pill_judge.JudgeCircuitBreaker(),
        )
    finally:
        con.close()


def test_stage_batch_matches_pre_change_golden(monkeypatch, tmp_path):
    golden = _golden()
    calls = []
    monkeypatch.setattr(pill_judge, "judge", make_judge(calls))
    db_path = tmp_path / "fixture.duckdb"
    build_fixture(db_path)

    inserts, deletes, counters = _run_stage_batch(db_path, calls)

    assert counters["judged"] == golden["counters"]["judged"]
    assert _normalised(inserts) == _normalised(golden["inserts"])
    assert sorted([list(d) for d in deletes]) == sorted(golden["deletes"])
    assert [{"category": c["category"], "urls": c["urls"]} for c in calls] == golden["judge_calls"]


def test_score_new_writes_the_same_tags_as_the_golden(monkeypatch, tmp_path):
    state = _run_score_new(monkeypatch, tmp_path)
    golden = _golden()
    assert state["result"]["judged"] == golden["counters"]["judged"]
    assert [{"category": c["category"], "urls": c["urls"]} for c in state["calls"]] == \
        golden["judge_calls"]
    assert state["watermark"].read_text().strip() == "11"

    import duckdb

    con = duckdb.connect(str(state["db_path"]), read_only=True)
    try:
        rows = con.execute(
            "SELECT article_id, source_type, category, matched_via, matched_detail, crawled_at "
            "FROM article_tags ORDER BY category, article_id, matched_via"
        ).fetchall()
    finally:
        con.close()
    expected = sorted(
        [list(r) for r in golden["final_tags"]],
        key=lambda r: (r[2], r[0], r[3]),
    )
    assert [list(r) for r in rows] == expected


